import type { Dictionary } from "@/lib/i18n/dictionaries";

type DanceMetricCopy = { shortLabel: string; hint: string };
type DanceExplainerCopy = {
  title: string;
  formula: string;
  why: string;
  target: string;
  source: string;
};

const metricKeys = [
  "FLOOR_UTILIZATION_PCT",
  "YIELD_PER_SQM",
  "INSTRUCTOR_SUB_RATE",
  "LEAD_FOLLOW_DELTA",
  "BLOCKED_REVENUE",
  "SOLO_COUPLE_RATIO",
  "NET_PROFIT_PER_CLASS",
  "PAYROLL_TO_REVENUE_PCT",
  "SEASON_VS_DROPIN_MIX",
  "L1_TO_L2_PROGRESSION",
  "CHURN_RISK_COUNT",
  "STYLE_CROSSOVER_PCT",
  "SOCIAL_CONVERSION_PCT",
] as const;

function pack(
  metrics: Record<(typeof metricKeys)[number], DanceMetricCopy>,
  explainers: Record<(typeof metricKeys)[number], DanceExplainerCopy>,
  meta: Omit<Dictionary["kpi"], "metrics" | "explainers">,
): Dictionary["kpi"] {
  return { ...meta, metrics, explainers };
}

